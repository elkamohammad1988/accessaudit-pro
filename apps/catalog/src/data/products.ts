interface Def {
  name: string;
  category: string;
  price: number;
  compareAt?: number;
  badges?: ProductBadge[];
  featured?: boolean;
  inStock?: boolean;
  colorways: Colorway[];
  materials: string[];
  dimensions: string;
  weight?: string;
  origin: string;
  short: string;
  long: string;
  care: string;
}

let arrival = 0;

function P(d: Def): Product {
  const slug = slugify(d.name);
  const r = hashFloat(slug);
  const badges = [...(d.badges ?? [])];
  if (d.compareAt && !badges.includes("sale")) badges.push("sale");
  return {
    slug,
    name: d.name,
    categorySlug: d.category,
    collectionSlugs: [], // filled by the collections module (single source of truth)
    price: d.price,
    compareAtPrice: d.compareAt,
    rating: Math.round((4.2 + r * 0.8) * 10) / 10,
    reviewCount: 18 + hashInt(slug + "rev", 512),
    badges,
    inStock: d.inStock ?? true,
    featured: d.featured ?? false,
    colorways: d.colorways,
    materials: d.materials,
    dimensions: d.dimensions,
    weight: d.weight,
    origin: d.origin,
    shortDescription: d.short,
    description: d.long,
    care: d.care,
    arrival: arrival++,
  };
}

